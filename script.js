/* =========================================================
   NAME GENERATOR
   ========================================================= */

function getGameName(file) {

    if (nameOverrides[file]) {
        return nameOverrides[file];
    }

    let name = file
        .replace(/^cl/i, "")
        .replace(/\.html$/i, "");

    name = name
        .replace(/([a-z])([A-Z])/g, "$1 $2")
        .replace(/[_-]+/g, " ")
        .replace(/\s+/g, " ")
        .trim();

    return name.replace(/\b\w/g, char =>
        char.toUpperCase()
    );
}


/* =========================================================
   CATEGORY DETECTION
   ========================================================= */

function getCategory(name) {

    const n = name.toLowerCase();


    /* SPORTS */

    if (
        n.includes("baseball") ||
        n.includes("basket") ||
        n.includes("soccer") ||
        n.includes("tennis") ||
        n.includes("football") ||
        n.includes("bmx") ||
        n.includes("bike") ||
        n.includes("bowling") ||
        n.includes("boxing") ||
        n.includes("table tennis")
    ) {
        return "sports";
    }


    /* PUZZLE */

    if (
        n.includes("2048") ||
        n.includes("maze") ||
        n.includes("chuzzle") ||
        n.includes("water sort") ||
        n.includes("puzzle") ||
        n.includes("drawing")
    ) {
        return "puzzle";
    }


    /* IDLE */

    if (
        n.includes("clicker") ||
        n.includes("idle") ||
        n.includes("capitalist") ||
        n.includes("tycoon") ||
        n.includes("bitlife")
    ) {
        return "idle";
    }


    /* SHOOTER */

    if (
        n.includes("doom") ||
        n.includes("shoot") ||
        n.includes("bullet") ||
        n.includes("sniper") ||
        n.includes("combat") ||
        n.includes("call of battle") ||
        n.includes("cod ")
    ) {
        return "shooter";
    }


    /* SURVIVAL */

    if (
        n.includes("survival") ||
        n.includes("nights") ||
        n.includes("drowned")
    ) {
        return "survival";
    }


    /* ARCADE */

    if (
        n.includes("arcade") ||
        n.includes("pinball") ||
        n.includes("centipede") ||
        n.includes("bomberman")
    ) {
        return "arcade";
    }


    return "action";
}


/* =========================================================
   BUILD GAME DATABASE
   ========================================================= */

const games = gameFiles.map(file => {

    const name = getGameName(file);

    return {
        name: name,
        file: file,
        category: getCategory(name),
        popular: false
    };

});


/* =========================================================
   REMOVE DUPLICATE FILES
   ========================================================= */

const uniqueGames = [];

const seen = new Set();

games.forEach(game => {

    if (!seen.has(game.file)) {

        seen.add(game.file);

        uniqueGames.push(game);

    }

});


/* =========================================================
   SORT A-Z
   ========================================================= */

uniqueGames.sort((a, b) =>
    a.name.localeCompare(
        b.name,
        undefined,
        {
            numeric: true,
            sensitivity: "base"
        }
    )
);


